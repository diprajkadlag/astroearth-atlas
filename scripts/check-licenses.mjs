#!/usr/bin/env node
/**
 * Checks the licenses of every production dependency (the third-party code
 * that the build ships to visitors) and keeps THIRD_PARTY_NOTICES.md current.
 *
 *   node scripts/check-licenses.mjs           check licenses and the notices file
 *   node scripts/check-licenses.mjs --write   check licenses, then rewrite the notices file
 *
 * Only permissive licenses may ship. Copyleft (GPL, LGPL, AGPL, MPL), custom
 * licenses (for example GSAP's) and packages without a license field fail.
 */
import { execSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const NOTICES_PATH = join(ROOT, "THIRD_PARTY_NOTICES.md");
const WRITE = process.argv.includes("--write");

const ALLOWED = new Set([
  "MIT",
  "ISC",
  "Apache-2.0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "0BSD",
  "CC0-1.0",
  "Unlicense",
  "BlueOak-1.0.0",
  "Zlib",
]);

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.[a-z]+)?$/i;

/** True when an SPDX expression allows use under permissive terms only. */
function isAllowed(expression) {
  const cleaned = expression.replace(/[()]/g, " ").replace(/\s+/g, " ").trim();
  if (/ OR /i.test(cleaned)) return cleaned.split(/ OR /i).some(isAllowed);
  if (/ AND /i.test(cleaned)) return cleaned.split(/ AND /i).every(isAllowed);
  return ALLOWED.has(cleaned);
}

function licenseOf(pkg) {
  if (typeof pkg.license === "string") return pkg.license;
  if (pkg.license && typeof pkg.license.type === "string") return pkg.license.type;
  if (Array.isArray(pkg.licenses)) {
    return pkg.licenses.map((entry) => entry.type ?? entry).join(" OR ");
  }
  return "UNKNOWN";
}

function repositoryOf(pkg) {
  const raw = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  if (!raw) return pkg.homepage ?? "not stated";
  return raw
    .replace(/^git\+/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/^github:/, "https://github.com/")
    .replace(/\.git$/, "");
}

/** Upstream license texts for packages whose npm tarball has no license file. */
const FALLBACK_TEXTS = join(ROOT, "scripts", "license-texts");

function licenseTexts(pkg) {
  const directory = pkg.realpath ?? pkg.path;
  const read = (path) => readFileSync(path, "utf8").replace(/\r\n/g, "\n").trim();
  const bundled =
    directory && existsSync(directory)
      ? readdirSync(directory)
          .filter((name) => LICENSE_FILE.test(name))
          .sort()
          .map((name) => ({ name, text: read(join(directory, name)) }))
      : [];
  if (bundled.length > 0) return bundled;
  const fallback = join(FALLBACK_TEXTS, `${pkg.name.replace("/", "__")}.txt`);
  return existsSync(fallback)
    ? [{ name: "LICENSE (from the upstream repository; the npm package has none)", text: read(fallback) }]
    : [];
}

/** Production packages, from npm's own dependency graph. */
function productionPackages() {
  const output = execSync("npm query .prod", {
    cwd: ROOT,
    encoding: "utf8",
    maxBuffer: 256 * 1024 * 1024,
  });
  const seen = new Map();
  for (const pkg of JSON.parse(output)) {
    if (!pkg.name || pkg.name === "medini-atlas") continue;
    const key = `${pkg.name}@${pkg.version}`;
    if (!seen.has(key)) seen.set(key, pkg);
  }
  return [...seen.values()].sort((a, b) =>
    `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`),
  );
}

function renderNotices(packages) {
  const lines = [
    "# Third-party notices",
    "",
    "Medini Atlas ships the following open-source packages in its built site.",
    "This file is generated by `npm run licenses:write`. Do not edit it by hand.",
    "",
  ];
  for (const pkg of packages) {
    lines.push(`## ${pkg.name} ${pkg.version}`, "");
    lines.push(`- License: ${licenseOf(pkg)}`);
    lines.push(`- Source: ${repositoryOf(pkg)}`, "");
    for (const { name, text } of licenseTexts(pkg)) {
      lines.push(`${name}:`, "", "````text", text, "````", "");
    }
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

const packages = productionPackages();
const rejected = packages.filter((pkg) => !isAllowed(licenseOf(pkg)));

for (const pkg of packages) {
  console.log(`${isAllowed(licenseOf(pkg)) ? "ok  " : "FAIL"}  ${pkg.name}@${pkg.version}  ${licenseOf(pkg)}`);
}

if (rejected.length > 0) {
  console.error(
    `\n${rejected.length} production package(s) have a license that may not ship:\n` +
      rejected.map((pkg) => `  ${pkg.name}@${pkg.version}: ${licenseOf(pkg)}`).join("\n"),
  );
  process.exit(1);
}

// Permissive licenses still require their notice to travel with the code.
const withoutText = packages.filter((pkg) => licenseTexts(pkg).length === 0);
if (withoutText.length > 0) {
  console.error(
    "\nThese production packages ship no license text. Add the upstream text as " +
      "scripts/license-texts/<package>.txt:\n" +
      withoutText.map((pkg) => `  ${pkg.name}@${pkg.version}`).join("\n"),
  );
  process.exit(1);
}

const notices = renderNotices(packages);
if (WRITE) {
  writeFileSync(NOTICES_PATH, notices);
  console.log(`\nWrote ${NOTICES_PATH} (${packages.length} packages).`);
} else {
  const current = existsSync(NOTICES_PATH)
    ? readFileSync(NOTICES_PATH, "utf8").replace(/\r\n/g, "\n")
    : "";
  if (current !== notices) {
    console.error("\nTHIRD_PARTY_NOTICES.md is out of date. Run `npm run licenses:write`.");
    process.exit(1);
  }
  console.log(`\nAll ${packages.length} production packages have permissive licenses. Notices are current.`);
}
